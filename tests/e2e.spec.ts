test('admin crea, sospende, resetta ed elimina un utente', async ({ page, browser }) => {
  await login(page)
  await page.goto('/admin')
  await expect(page.getByRole('row').filter({ hasText: process.env.E2E_EMAIL ?? '' })).toBeVisible()
  const email = `e2e-${Date.now()}@example.test`
  await page.getByRole('button', { name: 'Nuovo utente' }).click()
  await page.getByLabel('Nome').fill('Utente Test')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password iniziale').fill('PrimaPassword123!')
  await page.getByRole('button', { name: 'Crea utente' }).click()
  const row = page.getByRole('row').filter({ hasText: email })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'Sospendi' }).click()
  await expect(row).toContainText('Sospeso')
  await row.getByRole('button', { name: 'Riattiva' }).click()
  await expect(row).toContainText('Attivo')
  await row.getByRole('button', { name: 'Password' }).click()
  await page.getByRole('dialog', { name: 'Nuova password' }).locator('input[type=password]').fill('NuovaPassword123!')
  await page.getByRole('button', { name: 'Aggiorna password' }).click()
  const other = await browser.newContext()
  const userPage = await other.newPage()
  await userPage.goto('/login')
  await userPage.getByLabel('Email').fill(email)
  await userPage.getByLabel('Password').fill('NuovaPassword123!')
  await userPage.getByRole('button', { name: 'Accedi' }).click()
  await expect(userPage).toHaveURL(/\/app/)
  await userPage.getByRole('button', { name: 'Nuovo programma' }).click()
  await expect(userPage).toHaveURL(/\/app\/[^/]+/)
  const privateProgram = userPage.url()
  await page.goto(privateProgram)
  await expect(page.getByText('Programma non trovato')).toBeVisible()
  await page.goto('/admin')
  await expect(page.getByRole('row').filter({ hasText: email })).toBeVisible()
  await userPage.goto('/admin')
  await expect(userPage).toHaveURL(/\/app/)
  await other.close()
  await row.getByRole('button', { name: 'Elimina' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Elimina' }).click()
  await expect(row).toHaveCount(0)
})
