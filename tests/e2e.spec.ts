test('input multiplo, autosave e STOP su loop', async ({ page }) => {
  await login(page)
  await page.getByRole('button', { name: 'Nuovo programma' }).click()
  await expect(page.getByRole('button', { name: 'START' })).toBeEnabled({ timeout: 60_000 })
  await setCode(page, 'a = input("A? ")\nb = input("B? ")\nprint(a + " / " + b)')
  await expect(page.getByText('Salvato')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'START' })).toBeEnabled({ timeout: 60_000 })
  await expect(page.locator('.monaco-editor .view-lines')).toContainText('a = input')
  await page.getByRole('button', { name: 'START' }).click()
  await expect(page.getByLabel('Input programma')).toBeEnabled()
  await page.getByLabel('Input programma').fill('uno')
  await page.getByRole('button', { name: 'Invia' }).click()
  await expect(page.getByLabel('Input programma')).toBeEnabled()
  await page.getByLabel('Input programma').fill('due')
  await page.getByRole('button', { name: 'Invia' }).click()
  await expect(page.locator('.output-scroll')).toContainText('uno / due')
  await setCode(page, 'while True:\n    pass')
  await page.getByRole('button', { name: 'START' }).click()
  await expect(page.getByRole('button', { name: 'STOP' })).toBeVisible()
  await page.getByRole('button', { name: 'STOP' }).click()
  await expect(page.getByRole('button', { name: 'START' })).toBeEnabled({ timeout: 60_000 })
  await setCode(page, 'print("Dopo STOP")')
  await page.getByRole('button', { name: 'START' }).click()
  await expect(page.locator('.output-scroll')).toContainText('Dopo STOP')
})

test('STOP durante input, rinomina ed elimina', async ({ page }) => {
  await login(page)
  await page.getByRole('button', { name: 'Nuovo programma' }).click()
  await expect(page).toHaveURL(/\/app\/[^/]+/)
  const createdUrl = page.url()
  await expect(page.getByRole('button', { name: 'START' })).toBeEnabled({ timeout: 60_000 })
  await setCode(page, 'input("Attendo")')
  await page.getByRole('button', { name: 'START' }).click()
  await expect(page.getByLabel('Input programma')).toBeEnabled()
  await page.getByRole('button', { name: 'STOP' }).click()
  await expect(page.getByRole('button', { name: 'START' })).toBeEnabled({ timeout: 60_000 })
  await page.getByRole('button', { name: 'Senza titolo' }).first().click()
  await page.getByLabel('Nome programma').fill('Prova Emipy')
  await page.getByRole('button', { name: 'Salva' }).click()
  await expect(page.getByRole('button', { name: 'Prova Emipy' }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Azioni programma' }).click()
  await page.getByRole('menuitem', { name: 'Elimina' }).click()
  await page.getByRole('button', { name: 'Elimina' }).click()
  await expect(page).not.toHaveURL(createdUrl)
})

test('stderr, errore di sintassi ed errore runtime', async ({ page }) => {
  await login(page)
  await page.getByRole('button', { name: 'Nuovo programma' }).click()
  await expect(page.getByRole('button', { name: 'START' })).toBeEnabled({ timeout: 60_000 })
  await setCode(page, 'import sys\nprint("avviso", file=sys.stderr)')
  await page.getByRole('button', { name: 'START' }).click()
  await expect(page.locator('.output-scroll .text-destructive')).toContainText('avviso')
  await setCode(page, 'if True print("no")')
  await page.getByRole('button', { name: 'START' }).click()
  await expect(page.locator('.output-scroll .text-destructive')).toContainText('SyntaxError')
  await setCode(page, 'raise ValueError("errore test")')
  await page.getByRole('button', { name: 'START' }).click()
  await expect(page.locator('.output-scroll .text-destructive')).toContainText('ValueError: errore test')
})

